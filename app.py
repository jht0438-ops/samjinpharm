"""삼진제약 매출채권 회수 효율성 및 운전자본 분석기.
실제 공시자료 수치와 사용자가 선택하는 가정은 화면에서 분리 표시.
실행: streamlit run app_samjin_receivables.py
"""
import pandas as pd
import plotly.express as px
import streamlit as st

st.set_page_config(page_title="삼진제약 매출채권 회수 분석기", page_icon="💊", layout="wide")

# 출처: 삼진제약 2025 사업보고서(2026.03.16), 2026 반기보고서(2026.08.14)
# 매출액: 매출 및 수주상황 / 손익계산서, 원 단위 → 억 원
# 순매출채권: 주석 6의 '유동매출채권' 순장부금액(기타채권 제외), 천원 단위 → 억 원
# 2023말 순매출채권은 검증된 값이 없어 미입력. 2024 DSO는 계산하지 않음.
REVENUE = {"2023": 2921.28533737, "2024": 3083.49934442, "2025": 3091.33530719, "2026 상반기": 1477.04}
AR = {"2024": 624.98293, "2025": 602.61968, "2026 상반기": 557.32375}
PERIOD_DAYS = {"2025": 365, "2026 상반기": 181}

def dso(period):
    opening = AR["2024"] if period == "2025" else AR["2025"]
    return ((opening + AR[period]) / 2) / REVENUE[period] * PERIOD_DAYS[period]

def money(n):
    return f"{n:,.1f}억 원"

def explain(why, how, takeaway):
    for heading, content in [("왜 분석하나요?", why), ("어떻게 분석하나요?", how), ("이 탭을 통해 얻을 수 있는 결론은 무엇인가요?", takeaway)]:
        st.markdown(f"**{heading}**")
        st.write(content)
    st.divider()

st.title("💊 삼진제약 매출채권 회수 효율성 및 운전자본 분석기")
st.caption("실제 공시자료 분석 + 회수기간 단축 시뮬레이션 | 단위: 억 원")
st.info("**핵심 질문:** 매출채권 회수기간을 줄이면, 영업에 묶이는 자금을 얼마나 낮출 수 있을까? 공시 수치와 시뮬레이션 가정을 명확히 구분합니다.")

intro, receivables, efficiency, simulation, conclusion = st.tabs([
    "📘 개요", "① 매출·매출채권", "② 회수 효율성", "③ 개선 시뮬레이션", "④ 종합 결론"
])

with intro:
    st.header("프로그램 개요")
    st.markdown("""
### 1. 개발 배경과 목적
삼진제약은 기존 의약품 사업과 더불어 코프로모션 등으로 사업을 확대하고 있습니다. 매출이 증가해도 거래처에서 대금을 회수하기 전까지는 그만큼 현금을 자유롭게 사용할 수 없습니다. 특히 자금관리 직무의 **매출채권 수금 및 관리** 업무는 회수 속도와 운전자본 부담을 연결해서 이해하는 것이 중요합니다.

이에 **세무사 시험에서 익힌 회계 지식과 생성형 AI를 활용해** 삼진제약의 공시 매출액과 매출채권을 비교하고, 회수기간 단축이 평균 매출채권 점유액에 미치는 영향을 계산하는 프로그램을 구현했습니다.

### 2. 주요 기능
**① 매출·매출채권 현황:** 매출액 추이와 기말 순매출채권을 비교해 매출 성장과 채권 잔액의 방향이 같은지 확인합니다.

**② 회수 효율성:** 기초·기말 평균 순매출채권을 이용해 추정 매출채권 회전율과 회수기간(DSO)을 계산합니다. 연간과 반기 실적은 같은 기간의 매출을 사용하며 차이를 설명합니다.

**③ 개선 시뮬레이션:** 매출 규모와 회수기간 단축 목표를 설정하면 평균 매출채권 점유액 감소 추정액을 계산합니다. 가정값과 실제 공시값을 구분합니다.

**④ 종합 결론:** 회수기간 단축 목표별 자금 점유액 감소 효과를 숫자로 비교하고, 어떤 거래처·채권 자료를 우선 점검해야 하는지 제안합니다.

### 3. 분석의 특징과 한계
단순히 '수금을 잘해야 한다'고 결론 내리는 대신, **회수기간을 몇 일 줄였을 때 얼마의 자금이 매출채권에서 풀릴 수 있는지** 정량적으로 제시합니다. 다만 공시자료에는 거래처별 채권 잔액, 실제 수금일, 신용조건이 없어 연체 원인을 특정하거나 개선 효과의 실현을 보장할 수 없습니다.

### 4. 자금관리 직무와의 연결
분석을 통해 매출 증가율과 회수기간을 분리해서 판단하고, 회수기간 단축이 운전자본 부담을 줄이는 경로를 이해했습니다. 입사 후에는 거래처별 수금 예정·실적과 연체 구간을 점검하여, **자금 회수의 우선순위를 데이터로 판단하는 담당자**로 성장하겠습니다.
""")
    st.caption("자료: 삼진제약 2025년 사업보고서(2026.03.16), 2026년 반기보고서(2026.08.14).")

with receivables:
    st.header("① 매출액과 매출채권은 어떻게 변했을까?")
    explain(
        "매출이 늘어도 매출채권이 더 빠르게 늘면 자금이 채권에 묶일 수 있습니다. 반대로 채권 잔액이 줄었다고 해서 회수 효율이 반드시 개선된 것도 아닙니다.",
        "공시된 연간 매출액(2023~2025년)과 기말 순매출채권(2024~2026년 6월 말)을 각각 비교합니다. 매출은 일정 기간의 흐름, 매출채권은 특정 날짜의 잔액이므로 두 수치를 단순히 같은 종류의 값으로 해석하지 않습니다.",
        "2024→2025년 매출액은 소폭 증가한 반면, 기말 순매출채권은 감소했습니다. 다만 회수 효율 개선 여부는 다음 탭에서 평균채권과 기간 매출을 사용해 따로 검토해야 합니다."
    )
    c1,c2,c3 = st.columns(3)
    c1.metric("2025 매출액", money(REVENUE["2025"]), f"{(REVENUE['2025']/REVENUE['2024']-1)*100:+.2f}% (전년 대비)")
    c2.metric("2025말 순매출채권", money(AR["2025"]), f"{(AR['2025']/AR['2024']-1)*100:+.2f}% (전년말 대비)")
    c3.metric("2026.6말 순매출채권", money(AR["2026 상반기"]), f"{AR['2026 상반기']-AR['2025']:+.1f}억 원 (전년말 대비)")
    a,b=st.columns(2)
    with a:
        st.subheader("연간 매출액")
        df=pd.DataFrame({"연도":["2023","2024","2025"],"매출액(억 원)":[REVENUE[y] for y in ["2023","2024","2025"]]})
        fig=px.bar(df,x="연도",y="매출액(억 원)",text="매출액(억 원)")
        fig.update_traces(texttemplate="%{text:,.0f}",textposition="outside")
        fig.update_layout(height=310,margin=dict(t=25,b=0))
        st.plotly_chart(fig,use_container_width=True)
    with b:
        st.subheader("기말 순매출채권")
        df=pd.DataFrame({"기준일":["2024말","2025말","2026.6말"],"순매출채권(억 원)":[AR[y] for y in ["2024","2025","2026 상반기"]]})
        fig=px.line(df,x="기준일",y="순매출채권(억 원)",markers=True)
        fig.update_layout(height=310,margin=dict(t=25,b=0))
        st.plotly_chart(fig,use_container_width=True)
    st.warning("2026년 상반기 매출액은 6개월간 발생한 금액이므로 연간 매출과 직접 증감률을 비교하지 않습니다. 순매출채권은 기타채권을 제외한 유동 매출채권의 순장부금액입니다.")

with efficiency:
    st.header("② 실제 회수 효율은 어떻게 추정할까?")
    explain(
        "기말 잔액만 보면 매출이 발생하는 속도와 회수되는 속도를 구분하기 어렵습니다. 평균 매출채권과 매출액을 함께 고려한 회수기간 지표가 필요합니다.",
        "매출채권 회전율 = 해당 기간 매출액 ÷ 기초·기말 평균 순매출채권, 추정 회수기간(DSO) = 평균 순매출채권 ÷ 기간 매출액 × 기간 일수로 계산합니다. 2025년은 365일, 2026년 상반기는 181일을 적용합니다.",
        "공시자료로 2025년과 2026년 상반기의 추정 회수기간을 각각 산출할 수 있습니다. 다만 기간의 길이·계절성·매출 구성 차이가 있어 두 값을 곧바로 동일 조건의 성과평가로 단정해서는 안 됩니다."
    )
    data=[]
    for period in ["2025","2026 상반기"]:
        opening=AR["2024"] if period=="2025" else AR["2025"]
        avg=(opening+AR[period])/2
        data.append({"기간":period,"기간 매출액":REVENUE[period],"기초 순매출채권":opening,"기말 순매출채권":AR[period],"평균 순매출채권":avg,"회전율(회/기간)":REVENUE[period]/avg,"추정 DSO(일)":dso(period)})
    detail=pd.DataFrame(data)
    a,b=st.columns(2)
    a.metric("2025년 추정 회수기간",f"{dso('2025'):.1f}일")
    b.metric("2026년 상반기 추정 회수기간",f"{dso('2026 상반기'):.1f}일")
    st.dataframe(detail.style.format({"기간 매출액":"{:,.1f}","기초 순매출채권":"{:,.1f}","기말 순매출채권":"{:,.1f}","평균 순매출채권":"{:,.1f}","회전율(회/기간)":"{:.2f}","추정 DSO(일)":"{:.1f}"}),hide_index=True,use_container_width=True)
    fig=px.bar(detail,x="기간",y="추정 DSO(일)",text="추정 DSO(일)")
    fig.update_traces(texttemplate="%{text:.1f}일",textposition="outside")
    fig.update_layout(height=310,margin=dict(t=25,b=0))
    st.plotly_chart(fig,use_container_width=True)
    with st.expander("계산 예시 및 유의사항"):
        st.write(f"2025년 평균 순매출채권 = ({AR['2024']:.1f} + {AR['2025']:.1f}) ÷ 2 = {(AR['2024']+AR['2025'])/2:.1f}억 원")
        st.write(f"2025년 추정 DSO = 평균 순매출채권 ÷ 매출액 {REVENUE['2025']:.1f}억 원 × 365 = {dso('2025'):.1f}일")
        st.write("외상매출액이 별도로 확인되지 않아 전체 매출액을 대용했습니다. 기초·기말 2개 시점의 평균을 사용하므로 실제 거래처별 평균 회수일과 차이가 날 수 있습니다. 2023년 말 순매출채권은 검증되지 않아 2024년 DSO는 계산하지 않았습니다.")

with simulation:
    st.header("③ 회수기간을 줄이면 얼마의 자금 점유액이 감소할까?")
    explain(
        "회수기간이 길다는 사실만으로는 개선의 경제적 크기를 알기 어렵습니다. 회수기간을 며칠 단축했을 때 운전자본 점유액이 얼마나 달라지는지 숫자로 확인하기 위해서입니다.",
        "공시된 기간 매출액을 기준으로 '기간 매출액 ÷ 기간 일수 × 단축 일수'를 계산합니다. 매출 증가율과 단축 목표를 바꿔 여러 경우를 비교할 수 있습니다. 회수기간 단축은 기존 추정 DSO를 초과하지 못하도록 제한합니다.",
        "회수기간 1일 단축의 금액 효과와 3·5·10일 단축의 차이를 정량화할 수 있습니다. 결과는 평균 매출채권 점유액 감소 추정치이지 실제 수금액이나 추가 이익이 아닙니다."
    )
    st.caption("아래 슬라이더는 **가정값**입니다. 회사가 실제로 회수기간을 단축할 수 있다는 뜻은 아닙니다.")
    base=st.selectbox("기준 기간",["2025","2026 상반기"],index=0)
    period_days=PERIOD_DAYS[base]
    base_dso=dso(base)
    col1,col2=st.columns(2)
    with col1:
        growth=st.slider("매출 변화 가정 (%)",-20,30,0,1)
    with col2:
        target=st.slider("회수기간 단축 목표 (일)",0,int(base_dso),5,1)
    scenario_revenue=REVENUE[base]*(1+growth/100)
    daily=scenario_revenue/period_days
    released=daily*target
    before=daily*base_dso
    after=before-released
    a,b,c=st.columns(3)
    a.metric("가정 매출액",money(scenario_revenue))
    b.metric("회수기간 변화",f"{base_dso:.1f} → {base_dso-target:.1f}일")
    c.metric("평균 채권 점유액 감소 추정",money(released))
    fig=px.bar(pd.DataFrame({"구분":["개선 전","개선 후"],"평균 채권 점유액(억 원)":[before,after]}),x="구분",y="평균 채권 점유액(억 원)",text="평균 채권 점유액(억 원)")
    fig.update_traces(texttemplate="%{text:,.1f}",textposition="outside")
    fig.update_layout(height=315,margin=dict(t=25,b=0))
    st.plotly_chart(fig,use_container_width=True)
    st.subheader("단축 목표별 비교")
    targets=[t for t in [1,3,5,10,15] if t<=base_dso]
    compare=pd.DataFrame({"단축 목표(일)":targets,"점유액 감소 추정(억 원)":[daily*t for t in targets]})
    st.dataframe(compare.style.format({"점유액 감소 추정(억 원)":"{:,.1f}"}),hide_index=True,use_container_width=True)
    st.info(f"**핵심 수치:** {base} 기준 매출 변화율 {growth:+d}% 가정 시, 회수기간을 **1일 단축할 때 약 {daily:,.1f}억 원**, **{target}일 단축할 때 약 {released:,.1f}억 원**의 평균 매출채권 점유액 감소가 추정됩니다.")
    st.warning("단순 모형의 가정: 매출이 기간 내 균등하게 발생하고, 매출구성·외상판매 비율·거래조건이 동일하며, DSO 단축이 평균 매출채권 감소로 이어집니다. 실제 현금 확보액, 이익 증가액, 이자 절감액을 의미하지 않습니다.")

with conclusion:
    st.header("④ 종합 결론: 그래서 무엇을 발견했고, 어디부터 개선할까?")
    st.markdown("### 1. 공시로 확인한 사실")
    st.write(f"2024년 말 순매출채권은 **{money(AR['2024'])}**, 2025년 말은 **{money(AR['2025'])}**로 감소했습니다. 2025년 매출액은 전년 대비 **{(REVENUE['2025']/REVENUE['2024']-1)*100:+.2f}%** 변했습니다. 2026년 6월 말 순매출채권은 **{money(AR['2026 상반기'])}**입니다.")
    st.write(f"2025년 추정 DSO는 **{dso('2025'):.1f}일**, 2026년 상반기 추정 DSO는 **{dso('2026 상반기'):.1f}일**입니다. 다만 두 기간은 길이와 매출 계절성이 달라 회수 성과가 개선·악화됐다고 단정하지 않습니다.")
    st.markdown("### 2. 분석에서 새롭게 얻은 정량적 시사점")
