    st.warning("연구개발비는 회계상 비용·제조경비 등을 포함하는 공시 집계액으로, 해당 기간의 실제 연구개발 현금지출액과 같지 않습니다. 영업활동현금흐름도 연구개발에 전액 사용할 수 있는 자금이 아닙니다.")

